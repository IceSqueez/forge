#[cfg(test)]
mod tests {
    use super::humanize;

    #[test]
    fn a_glyph_name_reads_as_a_phrase_with_its_hyphens_spent_as_spaces() {
        for (name, expected) in [
            ("heart", "Heart"),
            ("star-filled", "Star filled"),
            ("device-gamepad-2", "Device gamepad 2"),
            ("Compass", "Compass"),
            ("", ""),
        ] {
            assert_eq!(humanize(name), expected, "name {name:?}");
        }
    }
}
